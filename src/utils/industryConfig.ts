export function getIndustryTemplate(
  industry: IndustryKey | undefined,
  customName?: string | null
): IndustryProfileTemplate {
  const key = industry && INDUSTRY_PROFILES[industry] ? industry : 'telecommunications';
  const base = INDUSTRY_PROFILES[key];
  if (key === 'other' && customName && customName.trim()) {
    return {
      ...base,
      label: customName.trim(),
      shortLabel: customName.trim(),
    };
  }
  return base;
}

export function buildDefaultChurnDefinition(
  industry: IndustryKey = 'telecommunications'
): ChurnDefinition {
  const tmpl = getIndustryTemplate(industry);
  return {
    ...tmpl.defaultChurnDefinition,
    confirmedByUser: false,
    confirmedAt: null,
  };
}

export function formatChurnCalculationExplanation(
  def: ChurnDefinition | undefined,
  churnedCount: number,
  totalCount: number
): string {
  const d = def || buildDefaultChurnDefinition('telecommunications');
  const denomSpec =
    DENOMINATOR_OPTIONS.find((o) => o.value === d.denominatorPopulation) || DENOMINATOR_OPTIONS[3];
  const periodLabel =
    REPORTING_PERIOD_OPTIONS.find((p) => p.value === d.reportingPeriod)?.label || 'Monthly';
  const rate = totalCount > 0 ? ((churnedCount / totalCount) * 100).toFixed(1) : '0.0';
  const inactivityNote =
    d.triggerType === 'inactivity' && d.inactivityDays
      ? ` (Inactivity rule: > ${d.inactivityDays} days without activity)`
      : '';
  return `${periodLabel} ${d.calculationMethod === 'period_based' ? 'period-based' : 'customer-based'} rate: ${churnedCount.toLocaleString()} churned ÷ ${totalCount.toLocaleString()} (${denomSpec.label}) = ${rate}%${inactivityNote}.`;
}

